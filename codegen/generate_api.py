#!/usr/bin/env python3
"""Generate Cython/C loader bindings for OpenAL-soft from registry/xml/al.xml.

Outputs (into src/openal_py/):
  - _al_api.pxd     Cython declarations: types + function prototypes
  - _api_table.c    function-pointer table + trampolines + dlopen loader
  - _api_table.h    C prototypes for the trampolines
  - _constants.py   AL / ALC constants (IntEnum) and extension name strings

Run:  python3 codegen/generate_api.py
CI must fail if this produces a diff (generated files are committed).
"""
from __future__ import annotations

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
XML = REPO / "openal-soft" / "registry" / "xml" / "al.xml"
OUT = REPO / "src" / "openal_py"

# Types used as function-pointer params: we bind the functions, not the callbacks.
FUNCPOINTER_TYPES = {
    "ALDEBUGPROCEXT", "ALEVENTPROCSOFT", "ALBUFFERCALLBACKTYPESOFT",
    "ALCEVENTPROCTYPESOFT", "LPALFOLDBACKCALLBACK",
}

# Opaque handle types the C headers declare as pointers to structs.
OPAQUE_TYPES = {"ALCdevice": "ALCdevice*", "ALCcontext": "ALCcontext*"}

HEADER = "// AUTO-GENERATED by codegen/generate_api.py -- DO NOT EDIT"
HEADER_PY = "# AUTO-GENERATED by codegen/generate_api.py -- DO NOT EDIT"


def norm_ws(s: str) -> str:
    return re.sub(r"\s+", " ", s).strip()


def parse_types(root) -> tuple[list[tuple[str, str]], dict[str, str]]:
    """Returns (typedefs, basetype name -> C base type)."""
    typedefs = []  # (cython_c_type, name)
    base = {}
    for types in root.findall("types"):
        ns = types.get("namespace")
        for t in types.findall("type"):
            if t.get("category") == "basetype":
                names = t.findall("name")
                if not names:
                    continue
                # base type = text before the first <name>; skip func-pointer typedefs
                c_type = norm_ws(t.text) if t.text else ""
                if not c_type.startswith("typedef") or "(" in c_type:
                    continue
                c_type = norm_ws(c_type[len("typedef"):])
                name = names[-1].text
                if c_type == "alsoft_impl_int64_t":
                    c_type = "long long"
                elif c_type == "alsoft_impl_uint64_t":
                    c_type = "unsigned long long"
                if name in base:
                    continue
                if name in OPAQUE_TYPES:
                    continue
                typedefs.append((c_type, name))
                base[name] = c_type
    return typedefs, base


def parse_enums(root) -> dict[str, list[tuple[str, object]]]:
    """namespace -> ordered [(name, value)] where value is int, alias str, or None."""
    out: dict[str, list[tuple[str, object]]] = {"AL": [], "ALC": []}

    def add(ns, name, value):
        # keep first definition; ignore duplicates/renames
        if any(n == name for n, _ in out[ns]):
            return
        out[ns].append((name, value))

    for enums in root.findall("enums"):
        ns = enums.get("namespace")
        if ns not in out:
            continue
        for e in enums.findall("enum"):
            v = e.get("value")
            add(ns, e.get("name"), int(v, 0) if (v is not None and (v.lstrip("-").isdigit() or v.lower().startswith("0x"))) else v)

    for feat in root.findall("feature"):
        ns = "ALC" if feat.get("api") == "alc" else "AL"
        for enums in feat.findall("enums"):
            for e in enums.findall("enum"):
                v = e.get("value")
                add(ns, e.get("name"), int(v, 0) if (v is not None and (v.lstrip("-").isdigit() or v.lower().startswith("0x"))) else v)
    return out


def parse_defines(root):
    """Numeric #define constants (e.g. ALC_VENDOR in the ALC types section)."""
    out = {"AL": [], "ALC": []}
    for types in root.findall("types"):
        ns = types.get("namespace")
        if ns not in out:
            continue
        for t in types.findall("type"):
            if t.get("category") != "define" or not t.text:
                continue
            m = re.search(r"#define\s+(AL[A-Z0-9]+)\s+([0-9a-fA-FxX]+)\s*$",
                          re.sub(r"\s+", " ", t.text).strip())
            if not m:
                continue
            name, value = m.group(1), int(m.group(2), 16)
            if any(n == name for n, _ in out[ns]):
                continue
            out[ns].append((name, value))
    return out


def parse_commands(root) -> list[dict]:
    """Extract commands: name, ret type, [(ctype, argname)], is_extension."""
    # Commands referenced inside <extensions> are optional at runtime.
    ext_names = set()
    for ext in root.findall("extensions/extension"):
        for req in ext.findall("require"):
            for ref in req.findall("command"):
                ext_names.add(ref.get("name"))
    cmds = []
    seen = set()
    for section in root.findall("commands"):
        for cmd in section.findall("command"):
            proto = cmd.find("proto")
            if proto is None:
                continue
            name = proto.find("name").text
            if name in seen:
                continue
            ptype_el = proto.find("ptype")
            if ptype_el is not None:
                parts = [ptype_el.text]
                if proto.text:
                    parts.insert(0, norm_ws(proto.text))
                if ptype_el.tail:
                    parts.append(norm_ws(ptype_el.tail))
                ret = " ".join(x for x in parts if x)
            else:
                ret = norm_ws(proto.text) if proto.text else "void"
            params = []
            skip = False
            for p in cmd.findall("param"):
                ptype_el = p.find("ptype")
                name_el = p.find("name")
                ptype = ptype_el.text if ptype_el is not None else (norm_ws(p.text) if p.text else "")
                if ptype in FUNCPOINTER_TYPES:
                    skip = True
                    break
                prefix = norm_ws(p.text) if (ptype_el is not None and p.text) else ""
                midsuffix = norm_ws(ptype_el.tail) if (ptype_el is not None and ptype_el.tail) else ""
                suffix = norm_ws(name_el.tail) if name_el is not None and name_el.tail else ""
                full = re.sub(r"\s+", " ", " ".join(x for x in (prefix, ptype, midsuffix, suffix) if x)).strip()
                params.append((full, name_el.text))
            if skip:
                continue
            seen.add(name)
            cmds.append({"name": name, "ret": ret, "params": params,
                         "ext": name in ext_names})
    return cmds


def resolve_ctype(t: str, typedef_names: set[str]) -> str:
    """Map a C type expression onto the typedef names available in the pxd."""
    t = t.strip()
    # split off const / pointer decorations
    is_const = t.startswith("const ")
    t = t[len("const "):] if is_const else t
    nstars = 0
    while t.endswith("*"):
        t = t[:-1].rstrip()
        nstars += 1
    t = t.strip()
    if t in OPAQUE_TYPES:
        base = OPAQUE_TYPES[t]
        stars = nstars
    else:
        base = t
        stars = nstars
    out = base + "*" * stars
    return ("const " + out) if is_const else out


def gen_pxd(cmds, typedefs) -> str:
    lines = [HEADER_PY, "", 'from cpython cimport PyMem_RawMalloc, PyMem_RawFree', "",
             'cdef extern from "AL/al.h":',
             "    ctypedef struct ALCdevice \"ALCdevice\"",
             "    ctypedef struct ALCcontext \"ALCcontext\"", ""]
    for c_type, name in typedefs:
        # avoid redefining the int64 aliases from <stdint.h> names
        lines.append(f"    ctypedef {c_type} {name}")
    lines += ["", 'cdef extern from "_api_table.h":',
              "    bint openal_py_init(const char* libpath, bint require_devices) nogil",
              '    bint openal_py_has_symbol(const char* name, ALCdevice* device) nogil',
              '    const char* openal_py_library_path() nogil', "",
              "    ctypedef void GUID", ""]
    for c in cmds:
        args = ", ".join(f"{ct} {an}".replace("struct _GUID", "GUID")
                         for ct, an in c["params"])
        ret = c['ret'].replace("struct _GUID", "GUID")
        lines.append(f"    {ret} {c['name']}({args}) nogil")
    return "\n".join(lines) + "\n"


def gen_c_header(cmds) -> str:
    lines = [HEADER, "#ifndef OPENAL_PY_API_TABLE_H", "#define OPENAL_PY_API_TABLE_H",
             "", "#include <AL/al.h>", "#include <AL/alc.h>", "#include <AL/alext.h>", "#include <stdint.h>",
             "", "#ifdef __cplusplus", 'extern "C" {', "#endif", ""]
    lines.append("int openal_py_init(const char* libpath, int require_devices);")
    lines.append("int openal_py_has_symbol(const char* name, ALCdevice* device);")
    lines.append("const char* openal_py_library_path(void);")
    lines.append("")
    for c in cmds:
        args = ", ".join(f"{ct} {an}" for ct, an in c["params"])
        lines.append(f"{c['ret']} {c['name']}({args});")
    lines += ["", "#ifdef __cplusplus", "}", "#endif", "",
              "#endif /* OPENAL_PY_API_TABLE_H */", ""]
    return "\n".join(lines)


def gen_c_source(cmds) -> str:
    # struct member: one fn pointer per command
    members = []
    for c in cmds:
        args = ", ".join(f"{ct} {an}" for ct, an in c["params"])
        args_typedef = args if args else "void"
        members.append(f"    {c['ret']} (*{c['name']})({args_typedef});")

    syms = []
    for c in cmds:
        if c.get("ext"):
            continue  # extension functions are optional; bound below anyway
        syms.append(f"    \"{c['name']}\",")

    trampolines = []
    for c in cmds:
        args = ", ".join(f"{ct} {an}" for ct, an in c["params"])
        body = f"fn.{c['name']}({', '.join(an for _, an in c['params'])})"
        ret = "return " if c["ret"] != "void" else ""
        trampolines.append(f"{c['ret']} {c['name']}({args}) {{ {ret}{body}; }}")

    src = f"""{HEADER}
#define _GNU_SOURCE   /* strdup, POSIX dlfcn */
#include "_api_table.h"

#ifdef _WIN32
#include <windows.h>
#else
#include <dlfcn.h>
#endif
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef struct {{
{chr(10).join(members)}
}} ALPyTable;

static ALPyTable fn;
static int initialized = 0;
static const char* g_libpath = NULL;
static void* g_handle = NULL;

static const char* const AL_PY_SYMBOLS[] = {{
{chr(10).join(syms)}
}};




static void* open_library(const char* path)
{{
#ifdef _WIN32
    wchar_t wide_path[32768];
    if (!MultiByteToWideChar(CP_UTF8, MB_ERR_INVALID_CHARS, path, -1,
                            wide_path, 32768))
        return NULL;
    return (void*)LoadLibraryW(wide_path);
#else
    return dlopen(path, RTLD_NOW | RTLD_LOCAL);
#endif
}}

static void close_library(void* handle)
{{
#ifdef _WIN32
    FreeLibrary((HMODULE)handle);
#else
    dlclose(handle);
#endif
}}

static void* lookup(void* handle, const char* name)
{{
#ifdef _WIN32
    return (void*)GetProcAddress((HMODULE)handle, name);
#else
    return dlsym(handle, name);
#endif
}}

int openal_py_init(const char* libpath, int require_devices)
{{
    void* handle;
    ALPyTable candidate;
    char* path_copy;

    if (initialized)
        return 1;
    if (!libpath || !libpath[0])
        return 0;
    handle = open_library(libpath);
    if (!handle)
        return 0;

    for (size_t i = 0; i < sizeof(AL_PY_SYMBOLS) / sizeof(AL_PY_SYMBOLS[0]); ++i)
    {{
        if (!lookup(handle, AL_PY_SYMBOLS[i]))
        {{
            close_library(handle);
            return 0;
        }}
    }}

"""
    binds = []
    for c in cmds:
        argtypes = ", ".join(f"{ct}" for ct, _ in c["params"]) if c["params"] else "void"
        binds.append(f"    candidate.{c['name']} = ({c['ret']} (*)({argtypes})) lookup(handle, \"{c['name']}\");")
    src += "\n".join(binds) + """
#undef OPENAL_PY_BIND

    if (require_devices)
    {
        ALCenum param = ALC_DEFAULT_DEVICE_SPECIFIER;
        if (candidate.alcIsExtensionPresent(NULL, "ALC_ENUMERATE_ALL_EXT"))
            param = 0x1013; /* ALC_ALL_DEVICES_SPECIFIER */
        else if (candidate.alcIsExtensionPresent(NULL, "ALC_ENUMERATION_EXT"))
            param = ALC_DEVICE_SPECIFIER;
        const ALCchar* devices = candidate.alcGetString(NULL, param);
        candidate.alcGetError(NULL);
        if (!devices || !devices[0])
        {
            close_library(handle);
            return 0;
        }
    }
    path_copy = malloc(strlen(libpath) + 1);
    if (!path_copy)
    {
        close_library(handle);
        return 0;
    }
    strcpy(path_copy, libpath);
    /* Commit only after validation; failed candidates leave no stale pointers. */
    fn = candidate;
    g_handle = handle;
    g_libpath = path_copy;
    initialized = 1;
    return 1;
}

static void* resolve_optional(const char* name, ALCdevice* device)
{
    if (strncmp(name, "alc", 3) == 0)
        return fn.alcGetProcAddress(device, name);
    return fn.alGetProcAddress(name);
}

int openal_py_has_symbol(const char* name, ALCdevice* device)
{
    if (!initialized)
        return 0;
    /* Proc-only addresses can be context/device-specific: refresh each use. */
"""
    for c in cmds:
        if not c.get("ext"):
            continue
        argtypes = ", ".join(ct for ct, _ in c["params"]) or "void"
        src += (f'    if (strcmp(name, "{c["name"]}") == 0) {{\n'
                f'        fn.{c["name"]} = '
                f'({c["ret"]} (*)({argtypes})) lookup(g_handle, name);\n'
                f'        if (!fn.{c["name"]}) fn.{c["name"]} = '
                f'({c["ret"]} (*)({argtypes})) resolve_optional(name, device);\n'
                f'        return fn.{c["name"]} != NULL;\n    }}\n')
    src += """
    return lookup(g_handle, name) != NULL;
}

const char* openal_py_library_path(void)
{
    return g_libpath;
}

"""
    src += "\n\n".join(trampolines) + "\n"
    return src


def gen_constants(enums) -> str:
    # Note: a plain class, not IntEnum -- OpenAL has intentional value
    # collisions across parameter groups (e.g. AL_MIN_GAIN/AL_MAX_GAIN),
    # which IntEnum would silently collapse into aliases.
    lines = [HEADER_PY,
             "",
             "",
             "class AL:",
             '    """OpenAL constants (al.h)."""',
             ""]
    # collect resolvable values
    def resolve(ns_list, name, value, depth=0):
        if depth > 4:
            return None
        if isinstance(value, int):
            return value
        if isinstance(value, str):
            for n, v in ns_list:
                if n == value:
                    return resolve(ns_list, value, v, depth + 1)
        return None

    # AL enum
    for name, value in enums["AL"]:
        v = resolve(enums["AL"], name, value)
        if v is None:
            continue
        lines.append(f"    {name} = {v}")
    lines += ["", "", "class ALC:", '    """ALC constants (alc.h)."""', ""]
    for name, value in enums["ALC"]:
        v = resolve(enums["ALC"], name, value)
        if v is None:
            continue
        lines.append(f"    {name} = {v}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    tree = ET.parse(XML)
    root = tree.getroot()

    typedefs, _base = parse_types(root)
    enums = parse_enums(root)
    for ns in ("AL", "ALC"):
        for name, value in parse_defines(root)[ns]:
            if not any(n == name for n, _ in enums[ns]):
                enums[ns].append((name, value))
    cmds = parse_commands(root)

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "_al_api.pxd").write_text(gen_pxd(cmds, typedefs))
    (OUT / "_api_table.h").write_text(gen_c_header(cmds))
    (OUT / "_api_table.c").write_text(gen_c_source(cmds))
    (OUT / "_constants.py").write_text(gen_constants(enums))

    print(f"generated: {len(cmds)} commands, "
          f"{len(enums['AL'])} AL + {len(enums['ALC'])} ALC constants")
    return 0


if __name__ == "__main__":
    sys.exit(main())
